/** Декоративные листы из нержавеющей стали — отдельный источник данных.
 *
 * Держим НЕ в pricelist.json намеренно: тот файл правится вручную/парсером,
 * а декор — своя подкатегория (лифты, кассы, интерьер) со своими
 * поверхностями (зеркало, 8K, Black Mirror, золото, шлифовка, узор DECO)
 * вместо стандартных 2B/BA/4N.
 *
 * Цены: Зеркало (BA) и Шлифованная (4N) — из прайса поставщика, пересчёт
 * ₽/т → ₽/лист по весу листа (площадь×толщина×плотность) ×1,05. Остальные
 * поверхности (8K, Black Mirror, золото, DECO) — «по запросу» (price=null):
 * у поставщика нет их финишной обработки (доп. полировка, PVD, тиснение),
 * базовая цена металла занизила бы премиальный финиш. Заменить реальными
 * позициями со склада, когда появятся.
 *
 * Названия поверхностей приведены к рыночным (inoxmarket и др.): зеркало,
 * суперзеркало 8K, чёрное зеркало (Black Mirror), золотое зеркало, шлифованная
 * (№4), узорные листы DECO. Фото фактур для узорных поверхностей — временные
 * плейсхолдеры (surfaces/*.png|jpg), заменить на собственные снимки склада.
 *
 * Русские подписи узоров DECO (галька/ромб/борозды и т.п.) — визуальные
 * описания по образцам, торговые названия рисунков уточнить у поставщика.
 * Изморозь (DECO 1) — подтверждённое имя.
 */

export interface DekorSku {
	hub: 'dekorativnye-listy';
	/** Ключ группы фактуры (zerkalo/zoloto/shlifovka/uzor) — используется как
	 *  «Тип» фильтра в PriceTable. */
	sub: string | null;
	grade: string | null;
	roll: string | null;
	alloy: string | null;
	/** Название поверхности: «Зеркало», «8K», «Black Mirror», «DECO 1» и т.п. */
	surface: string;
	/** Толщина листа, мм (как строка — единообразно с pricelist). */
	size: string;
	/** Формат листа «ширина×длина» в ASCII: «1250x2500». Отдельное поле, чтобы
	 *  фильтр «Формат» в PriceTable не зависел от разбора названия. */
	format: string;
	/** Словесный цвет поверхности: сталь / чёрный / золото. */
	color: string;
	unit: string;
	price: number | null;
	priceUnit: number | null;
	slug: string;
	dlina: string | null;
	fact: string | null;
	ostatok: number | null;
	name: string;
}

