/** Подписи поверхностей для меток фильтра/чипов — закрывают оба варианта
 *  поиска (люди вбивают и «8K», и «суперзеркало»; и «DECO 1», и «изморозь»).
 *  Строится из META: если имя = русскому, дублировать не нужно. */
export const DEKOR_SURFACE_LABELS: Record<string, string> = Object.fromEntries(
	Object.entries(DEKOR_SURFACE_META).map(([code, m]) => {
		const same = code.trim().toLowerCase() === m.ru.trim().toLowerCase();
		return [code, same ? code : `${code} — ${m.ru}`];
	}),
);

const fmtHuman = (f: string): string => f.replace('x', '×');

function mk(surface: string, grade: string, thickness: string, format: string, price: number | null = null): DekorSku {
	const meta = DEKOR_SURFACE_META[surface];
	const t = thickness.replace('.', ',');
	const gradeSlug = grade.toLowerCase().replace(/\s+/g, '-');
	const paren = meta.ru.trim().toLowerCase() === surface.trim().toLowerCase()
		? ''
		: ` (${meta.ru.toLowerCase()})`;
	return {
		hub: 'dekorativnye-listy',
		sub: meta.group,
		grade,
		roll: null,
		alloy: null,
		surface,
		size: thickness,
		format,
		color: meta.color,
		unit: 'лист',
		price,
		priceUnit: price,
		slug: `list-dekorativnyy-${meta.slugKey}-${gradeSlug}-${t.replace(',', '_')}x${format.replace('x', '-')}`,
		dlina: null,
		fact: null,
		ostatok: null,
		name: `Лист нержавеющий декоративный ${grade} ${t}×${fmtHuman(format)} ${surface}${paren}`,
	};
}

