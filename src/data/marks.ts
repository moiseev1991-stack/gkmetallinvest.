/** Список slug'ов всех марок — для роутинга. */
export const markSlugs = marks.map((m) => m.slug);

/** Проверка: является ли указанный slug марочной посадочной (а не товаром). */
export function isMarkSlug(slug: string): boolean {
	return marks.some((m) => m.slug === slug);
}

/** Какие марки доступны для указанного хаба. */
export function marksForHub(hub: string): MarkInfo[] {
	return marks.filter((m) => m.hubs.includes(hub as any));
}
