/** Трубопроводная арматура — данные для хабов и посадочных страниц линеек.
 *
 * Пока все позиции идут «по запросу» (без прайса) — рендерим HubRequest.
 * Линейки сгруппированы по типу изделия (а не по каждому исполнению),
 * чтобы страницы были содержательными, а не тонкими дублями друг друга.
 *
 * Источник: заводские прайсы «Маршал» и «Медэкс» (public/prai.20).
 */

export interface ArmaturaExecution {
	/** Исполнение / вариант линейки. */
	name: string;
	/** Заводская маркировка (по ГОСТ 4666-2015). */
	mark: string;
	/** Короткое пояснение: среда, сталь, особенность. */
	note?: string;
}

export interface ArmaturaLine {
	slug: string;
	/** H1 посадочной страницы. */
	title: string;
	/** Короткий заголовок для карточки в хабе. */
	cardTitle: string;
	/** Подзаголовок карточки / лид. */
	summary: string;
	/** Вводные абзацы страницы линейки. */
	intro: string[];
	/** Исполнения линейки (таблица маркировок). */
	executions: ArmaturaExecution[];
	/** Метка бренда-производителя. */
	brand?: string;
	faq?: { q: string; a: string }[];
}

