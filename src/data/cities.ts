/**
 * Городские лендинги — топ-5 регионов под геозапросы вида
 * «лист нержавеющий купить в Москве». Каждая запись задаёт уникальный
 * блок про доставку (расстояние / сроки), чтобы страница не была
 * пустой копией хаба.
 */
export interface CityInfo {
	slug: string; // префиксуется как /<hub>/v-<slug>/
	name: string; // именительный, для H1
	loc: string; // предложный, для заголовков «в Москве»
	from: string; // родительный, для «доставка из Нижнего Новгорода в Москву» — фактически винительный
	region?: string;
	distance: number; // км от Нижнего Новгорода
	transit: string; // ориентировочные сроки
	highlights: string[]; // 2-3 кратких bullet-преимущества под этот регион
}

