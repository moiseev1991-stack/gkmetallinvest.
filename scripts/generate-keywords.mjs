const clusters = {};
const all = new Set();

const add = (cluster, list) => {
	clusters[cluster] = clusters[cluster] || new Set();
	for (const k of list) {
		const v = k.trim().toLowerCase().replace(/\s+/g, ' ');
		if (v.length >= 4 && v.length <= 80) {
			clusters[cluster].add(v);
			all.add(v);
		}
	}
};

