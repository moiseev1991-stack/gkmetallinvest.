function clusterDescription(c) {
	const map = {
		'00-generic': 'Общая лексика (нержавейка / металлопрокат)',
		'10-hubs': 'Базовые названия хабов',
		'20-hub-commerce': 'Хаб + купить/цена/прайс/опт',
		'30-hub-mark': 'Хаб + марка (AISI / ГОСТ)',
		'35-mark-commerce': 'Марка отдельно + коммерция',
		'40-hub-city': 'Хаб + город (15 регионов)',
		'45-mark-city': 'Марка + город (топ-5 марок)',
		'50-sizes': 'Размерные хвосты (лист/круг/труба/проф.труба)',
		'55-surfaces': 'Поверхности (шлиф / 2B / BA / зеркальный)',
		'60-services': 'Услуги (резка / полировка / перфорация)',
		'70-info': 'Информационные (вес / плотность / ГОСТ / расшифровка)',
		'80-applications': 'Применение (пищевая / медицинская / морская)',
	};
	const base = c.split('/')[0];
	const sub = c.split('/')[1];
	const baseDesc = map[base] || c;
	return sub ? `${baseDesc} → ${sub}` : baseDesc;
}
